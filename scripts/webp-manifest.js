const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
function walk(dir, files = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, files);
    else if (e.isFile() && /\.webp$/i.test(p)) files.push(p);
  }
  return files;
}

const webps = walk(path.join(root, 'assets/img'));
const list = webps
  .map(p => '/' + path.relative(root, p).split(path.sep).join('/'))
  .sort();

const out = path.join(root, 'js/webp-manifest.js');
fs.writeFileSync(out,
  '// Auto-generated by scripts/webp-manifest.js — list of available WebP files.\n' +
  'window.__WEBP_MANIFEST__ = new Set(' + JSON.stringify(list, null, 2) + ');\n');
console.log('Wrote', list.length, 'WebP entries to', path.relative(root, out));
